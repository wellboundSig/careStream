#!/usr/bin/env node
/**
 * generate-asset-people-seed.mjs — CSV employee lists → 0038_asset_mgt_people_seed.sql
 *
 * Reads:  db/seed-data/asset-mgt-field-staff.csv   (Id, Name, Status, Discipline, Hire Date)
 *         db/seed-data/asset-mgt-office-staff.csv  (Id, Name, Status, Hire Date)
 * Writes: db/migrations/0038_asset_mgt_people_seed.sql
 *
 * People rows get deterministic rec_ids (recamuf#### field / recamuo####
 * office) and every insert is ON CONFLICT DO NOTHING, so re-running the
 * migration (or regenerating after a CSV refresh) never duplicates anyone.
 *
 * Baseline (housekeeping) assignments per the rollout spec:
 *   - every FIELD clinician: Tablet ×1, Pointcare ACCESS, Homecare Homebase PROFILE
 *   - every OFFICE employee: Homecare Homebase ACCESS (login profile)
 * Backfill dates are NULL on purpose — we don't know when people actually
 * received things, and inventing dates would poison historical reports.
 *
 * Duplicate names within a file (HR double-entries, e.g. the same person
 * keyed twice) are collapsed to the first occurrence and listed in a SQL
 * comment for review.
 *
 * Usage: node db/generate-asset-people-seed.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)));

const SOL_HCHB = 'recamsolhchb';
const SOL_POINTCARE = 'recamsolpointcare';
const HW_TABLET = 'recamhwtablet';
const CHUNK = 40; // rows per INSERT — keeps each statement well under the RDS Data API 64KB SQL cap

// ── Tiny CSV parser (quoted fields, embedded commas) ─────────────────────────
function parseCsv(text) {
  const rows = [];
  let row = [];
  let cur = '';
  let inQ = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (inQ) {
      if (ch === '"') {
        if (text[i + 1] === '"') { cur += '"'; i++; } else inQ = false;
      } else cur += ch;
    } else if (ch === '"') inQ = true;
    else if (ch === ',') { row.push(cur); cur = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(cur); cur = '';
      if (row.some((c) => c.trim() !== '')) rows.push(row);
      row = [];
    } else cur += ch;
  }
  row.push(cur);
  if (row.some((c) => c.trim() !== '')) rows.push(row);
  return rows;
}

function mdyToIso(s) {
  const m = String(s || '').trim().match(/^(\d{1,2})\/(\d{1,2})\/(\d{4})$/);
  if (!m) return null;
  return `${m[3]}-${m[1].padStart(2, '0')}-${m[2].padStart(2, '0')}`;
}

function splitName(full) {
  const t = String(full || '').trim();
  const comma = t.indexOf(',');
  if (comma >= 0) {
    return { last: t.slice(0, comma).trim(), first: t.slice(comma + 1).trim() };
  }
  const parts = t.split(/\s+/);
  return { last: parts.pop() || '', first: parts.join(' ') };
}

const q = (v) => (v === null || v === undefined || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

function loadStaff(file, staffType, hasDiscipline, recPrefix) {
  const rows = parseCsv(fs.readFileSync(path.join(ROOT, 'seed-data', file), 'utf8'));
  const header = rows.shift().map((h) => h.trim().toLowerCase());
  const col = (name) => header.indexOf(name);
  const iId = col('id');
  const iName = col('name');
  const iStatus = col('status');
  const iDisc = hasDiscipline ? col('discipline') : -1;
  const iHire = col('hire date');

  const seen = new Map(); // normalized name -> first row
  const dupes = [];
  const out = [];
  let n = 0;
  for (const r of rows) {
    const name = String(r[iName] || '').trim();
    if (!name) continue;
    const key = name.toLowerCase().replace(/\s+/g, ' ');
    if (seen.has(key)) { dupes.push(`${name} (employee ids ${seen.get(key)} / ${String(r[iId]).trim()})`); continue; }
    seen.set(key, String(r[iId] || '').trim());
    n++;
    const { first, last } = splitName(name);
    out.push({
      recId: `${recPrefix}${String(n).padStart(4, '0')}`,
      employeeId: String(r[iId] || '').trim(),
      first,
      last,
      name: `${first} ${last}`.trim(),
      staffType,
      discipline: iDisc >= 0 ? String(r[iDisc] || '').trim() : '',
      status: String(r[iStatus] || '').trim() === 'Active' ? 'Active' : 'Inactive',
      hireDate: mdyToIso(r[iHire]),
    });
  }
  return { people: out, dupes };
}

const field = loadStaff('asset-mgt-field-staff.csv', 'FIELD', true, 'recamuf');
const office = loadStaff('asset-mgt-office-staff.csv', 'OFFICE', false, 'recamuo');
const people = [...field.people, ...office.people];

const lines = [];
lines.push('-- 0038_asset_mgt_people_seed.sql — generated by db/generate-asset-people-seed.mjs.');
lines.push('-- Regenerate from db/seed-data/*.csv; do not hand-edit.');
lines.push(`-- ${field.people.length} field clinicians + ${office.people.length} office staff.`);
lines.push('-- Backfill dates are intentionally NULL (unknown), per the rollout plan.');
for (const d of [...field.dupes, ...office.dupes]) {
  lines.push(`-- deduped double-entry: ${d}`);
}
lines.push('');

// People
for (let i = 0; i < people.length; i += CHUNK) {
  const chunk = people.slice(i, i + CHUNK);
  lines.push('INSERT INTO "asset_mgt_users"');
  lines.push('  ("rec_id", "id", "employee_id", "first_name", "last_name", "name", "staff_type", "discipline", "status", "hire_date", "source") VALUES');
  lines.push(chunk.map((p) =>
    `  (${q(p.recId)}, ${q(p.recId)}, ${q(p.employeeId)}, ${q(p.first)}, ${q(p.last)}, ${q(p.name)}, ${q(p.staffType)}, ${q(p.discipline || null)}, ${q(p.status)}, ${p.hireDate ? `${q(p.hireDate)}::date` : 'NULL'}, 'SEED')`,
  ).join(',\n') + '\nON CONFLICT ("rec_id") DO NOTHING;');
  lines.push('');
}

// Baseline solution assignments
const solRows = [];
let sn = 0;
const pushSol = (userRecId, solId, rel) => {
  sn++;
  solRows.push(`  ('recamus${String(sn).padStart(5, '0')}', 'recamus${String(sn).padStart(5, '0')}', ${q(userRecId)}, ${q(solId)}, ${q(rel)}, 'Backfill seed')`);
};
for (const p of field.people) {
  pushSol(p.recId, SOL_POINTCARE, 'ACCESS');
  pushSol(p.recId, SOL_HCHB, 'PROFILE');
}
for (const p of office.people) {
  pushSol(p.recId, SOL_HCHB, 'ACCESS');
}
for (let i = 0; i < solRows.length; i += CHUNK) {
  lines.push('INSERT INTO "asset_mgt_user_solutions"');
  lines.push('  ("rec_id", "id", "user_id", "solution_id", "relationship_type", "notes") VALUES');
  lines.push(solRows.slice(i, i + CHUNK).join(',\n') + '\nON CONFLICT ("rec_id") DO NOTHING;');
  lines.push('');
}

// Baseline hardware: every field clinician has a tablet.
const hwRows = field.people.map((p, i) => {
  const rid = `recamuh${String(i + 1).padStart(5, '0')}`;
  return `  ('${rid}', '${rid}', ${q(p.recId)}, '${HW_TABLET}', 1, 'Backfill seed')`;
});
for (let i = 0; i < hwRows.length; i += CHUNK) {
  lines.push('INSERT INTO "asset_mgt_user_hardware"');
  lines.push('  ("rec_id", "id", "user_id", "hardware_type_id", "quantity", "notes") VALUES');
  lines.push(hwRows.slice(i, i + CHUNK).join(',\n') + '\nON CONFLICT ("rec_id") DO NOTHING;');
  lines.push('');
}

const outPath = path.join(ROOT, 'migrations', '0038_asset_mgt_people_seed.sql');
fs.writeFileSync(outPath, lines.join('\n'));
console.log(`Wrote ${outPath}`);
console.log(`  people: ${people.length} (${field.people.length} field, ${office.people.length} office)`);
console.log(`  solution assignments: ${solRows.length}, hardware assignments: ${hwRows.length}`);
if (field.dupes.length || office.dupes.length) {
  console.log(`  deduped: ${[...field.dupes, ...office.dupes].join(' | ')}`);
}
